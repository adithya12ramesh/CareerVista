import os
import tkinter as tk
from PIL import Image, ImageTk
ASSETS_DIR = os.path.join(os.path.dirname(__file__), "assets")
def show_next_screen():
    left_frame.pack_forget()
    right_frame.pack_forget()
    next_frame = tk.Frame(root, width=800, height=500, bg="white")
    next_frame.pack(fill="both")
    next_label = tk.Label(next_frame, text="Welcome to the next screen!", font=("Arial", 24, "bold"), bg="white")
    next_label.pack(pady=100)
root = tk.Tk()
root.title("CareerVista Home")
root.geometry("800x500")
root.configure(bg="white")
left_frame = tk.Frame(root, width=400, height=500, bg="#f1f1f1")
left_frame.pack(side="left", fill="both")
left_frame.pack_propagate(False)
cap_image = Image.open(os.path.join(ASSETS_DIR, "graduation_cap.jpg"))
cap_image = cap_image.resize((250, 250), Image.Resampling.LANCZOS)
cap_photo = ImageTk.PhotoImage(cap_image)
cap_label = tk.Label(left_frame, image=cap_photo, bg="#f1f1f1")
cap_label.place(relx=0.5, rely=0.5, anchor="center")
right_frame = tk.Frame(root, width=400, height=500, bg="white")
right_frame.pack(side="right", fill="both")
right_frame.pack_propagate(False)
logo_image = Image.open(os.path.join(ASSETS_DIR, "compass_logo.png"))
logo_image = logo_image.resize((60, 60), Image.Resampling.LANCZOS)
logo_photo = ImageTk.PhotoImage(logo_image)
logo_label = tk.Label(right_frame, image=logo_photo, bg="white")
logo_label.pack(pady=(100, 10))
login_label = tk.Label(right_frame, text="LOGIN", font=("Arial", 24, "bold"), bg="white")
login_label.pack()
subtext_label = tk.Label(right_frame, text="CareerVista Login", font=("Arial", 12), fg="gray", bg="white")
subtext_label.pack(pady=(5, 30))
sign_in_button = tk.Button(right_frame, text="Sign In", bg="black", fg="white", font=("Arial", 10), padx=20, pady=5, borderwidth=0, command=show_next_screen)
sign_in_button.pack()
if __name__ == "__main__":
    root.mainloop()
